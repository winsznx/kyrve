export type EpochStage =
  | "cacheProvider"
  | "accumulate"
  | "finalize"
  | "reduce"
  | "publish"
  | "allocate";

export interface EpochTransaction {
  readonly stage: EpochStage;
  /** Deterministic index within the stage. Never a timestamp or random value — Workflow step
   *  names are memoisation keys (PRD v1.1 A-20). */
  readonly chunkIndex: number;
  readonly units: number;
  readonly gas: number;
}

export interface EpochPlan {
  readonly providers: number;
  readonly leaves: number;
  readonly cells: number;
  /** Stage C cell gas alone — the load-bearing measured number in the Day 0 table. */
  readonly cellGas: number;
  /** Complete per-epoch gas including chunk overhead and publishWinner. */
  readonly totalGas: number;
  readonly transactions: readonly EpochTransaction[];
  readonly transactionCount: number;
  /** Highest single-transaction gas in the plan. Must stay under the ceiling. */
  readonly peakTransactionGas: number;
}

function chunk(total: number, per: number): number[] {
  const sizes: number[] = [];
  let remaining = total;
  while (remaining > 0) {
    const take = Math.min(per, remaining);
    sizes.push(take);
    remaining -= take;
  }
  return sizes;
}

/**
 * Produces the real, stage-aware transaction schedule for one epoch.
 *
 * This is what the keeper plans against. Stages cannot be merged across a transaction boundary
 * because each is a distinct external call with its own idempotency key, so the transaction count
 * is derived from a genuine schedule rather than by dividing total gas by the ceiling.
 *
 * @param cellsPerChunk defaults to the recommended 256, not the 311 maximum, so a chunk retains
 *        roughly 18% headroom against the gas ceiling.
 */
export function planEpoch(
  providers: number,
  leaves: number,
  cellsPerChunk: number = OPERATION_BUDGET.recommendedChunkCells,
): EpochPlan {
  assertPositiveInteger(providers, "providers");
  assertPositiveInteger(leaves, "leaves");
  assertChunkWithinBudget(cellsPerChunk);

  const transactions: EpochTransaction[] = [];

  transactions.push({
    stage: "cacheProvider",
    chunkIndex: 0,
    units: providers,
    gas: providers * STAGE_GAS.cacheProvider,
  });

  const cells = providers * leaves;
  chunk(cells, cellsPerChunk).forEach((size, i) => {
    transactions.push({
      stage: "accumulate",
      chunkIndex: i,
      units: size,
      gas: size * STAGE_GAS.accumulateCell + STAGE_GAS.accumulateChunkOverhead,
    });
  });

  chunk(leaves, OPERATION_BUDGET.maxLeavesPerFinalizeChunk).forEach((size, i) => {
    transactions.push({
      stage: "finalize",
      chunkIndex: i,
      units: size,
      gas: size * STAGE_GAS.finalizeLeaf,
    });
  });

  chunk(leaves, OPERATION_BUDGET.maxLeavesPerReduceChunk).forEach((size, i) => {
    transactions.push({
      stage: "reduce",
      chunkIndex: i,
      units: size,
      gas: size * STAGE_GAS.reduceWinnerLeaf,
    });
  });

  transactions.push({
    stage: "publish",
    chunkIndex: 0,
    units: 1,
    gas: STAGE_GAS.publishWinner,
  });

  transactions.push({
    stage: "allocate",
    chunkIndex: 0,
    units: providers,
    gas: providers * STAGE_GAS.allocate,
  });

  const totalGas = transactions.reduce((sum, t) => sum + t.gas, 0);
  const peakTransactionGas = transactions.reduce((max, t) => Math.max(max, t.gas), 0);

  if (peakTransactionGas > OPERATION_BUDGET.transactionGasCeiling) {
    throw new Error(
      `Epoch plan for ${providers}x${leaves} has a ${peakTransactionGas} gas transaction, above the ` +
        `${OPERATION_BUDGET.transactionGasCeiling} ceiling. Reduce cellsPerChunk or the universe size.`,
    );
  }

  return {
    providers,
    leaves,
    cells,
    cellGas: cells * STAGE_GAS.accumulateCell,
    totalGas,
    transactions,
    transactionCount: transactions.length,
    peakTransactionGas,
  };
}

/**
 * Reproduces the capacity table published in docs/day0/OPERATION-BUDGET.md section 5, exactly.
 *
 * Retained so the Day 0 evidence stays checkable against this repository. It is NOT the model
 * production code should use — see the Phase 1 correction at the top of this file.
 */
export function publishedEpochGas(providers: number, leaves: number): number {
  assertPositiveInteger(providers, "providers");
  assertPositiveInteger(leaves, "leaves");
  return (
    providers * leaves * STAGE_GAS.accumulateCell +
    providers * (STAGE_GAS.cacheProvider + STAGE_GAS.allocate) +
    leaves * (STAGE_GAS.finalizeLeaf + STAGE_GAS.reduceWinnerLeaf)
  );
}

/** Throws if a proposed chunk would exceed the measured per-transaction budget. */
export function assertChunkWithinBudget(cells: number): void {
  assertPositiveInteger(cells, "cells");
  if (cells > OPERATION_BUDGET.maxCellsPerTransaction) {
    throw new Error(
      `Chunk of ${cells} cells exceeds the measured budget of ` +
        `${OPERATION_BUDGET.maxCellsPerTransaction} cells per transaction ` +
        `(${OPERATION_BUDGET.transactionGasCeiling} gas ceiling, ${STAGE_GAS.accumulateCell} gas per cell, ` +
        `${STAGE_GAS.accumulateChunkOverhead} chunk overhead). docs/day0/OPERATION-BUDGET.md is binding.`,
    );
  }
}

function assertPositiveInteger(value: number, name: string): void {
  if (!Number.isInteger(value) || value <= 0) {
    throw new Error(`${name} must be a positive integer, received ${value}`);
  }
}
