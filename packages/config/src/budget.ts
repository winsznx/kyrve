/**
 * Normative operation budget — the executable form of `docs/day0/OPERATION-BUDGET.md`.
 *
 * Every gas figure here is MEASURED against the real local Nox stack during Day 0, not estimated.
 * Raw data: `evidence/day0/nox-runtime/`. These values constrain the confidential curve engine
 * that Phase 2 builds; Phase 1 exports them so the keeper, the workflow step planner and the
 * deployment manifests are sized against measured reality rather than a guess.
 *
 * ---------------------------------------------------------------------------------------------
 * PHASE 1 CORRECTION (delta P-1, docs/phase1/PRD-DELTA.md)
 *
 * The capacity table published in OPERATION-BUDGET.md section 5 is generated by the model
 *
 *     cells x accumulateCell  +  providers x (cacheProvider + allocate)  +  leaves x (finalizeLeaf + reduceWinnerLeaf)
 *
 * which reproduces every published row to the exact wei. That model omits two costs that are
 * genuinely incurred once per epoch: Stage C's per-chunk fixed overhead (166,954 gas x chunk
 * count) and Stage E2 `publishWinner` (90,076 gas). Per-epoch gas is therefore understated by
 * 0.72% at 16x128 and 2.42% at 4x16.
 *
 * `publishedEpochGas()` reproduces the Day 0 table exactly so the evidence stays checkable.
 * `planEpoch()` is the corrected model and is what production code must use. The Day 0
 * conclusion is unchanged: the full 16x128 universe remains executable.
 *
 * Stage A `seedProvider` is excluded from both, deliberately and correctly — a provider mandate
 * is sealed once and reused across every subsequent epoch, so it is not an epoch cost. It is
 * exported separately as `STAGE_GAS.seedProvider` for mandate-submission sizing.
 * ---------------------------------------------------------------------------------------------
 */

